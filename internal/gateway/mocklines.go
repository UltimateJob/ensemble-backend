// extractName 从 system prompt 里抠出角色名。
// 编排器写的是：你的名字是「林」
func extractName(system string) string {
	const marker = "你的名字是「"
	i := strings.Index(system, marker)
	if i < 0 {
		return ""
	}
	rest := system[i+len(marker):]
	j := strings.Index(rest, "」")
	if j < 0 {
		return ""
	}
	return rest[:j]
}

// isAnimeScene 判断 system prompt 是否来自二次元场景。
// 依据是两处固定文案：编排器写入的群名「二次元茶话会」，
// 以及角色库人设里的「（出自《作品》）」。
func isAnimeScene(system string) bool {
	return strings.Contains(system, "二次元") || strings.Contains(system, "出自《")
}

// 每个台词池上次用的下标，用于「不连着说同一句」的保护。
var (
	mockMu   sync.Mutex
	mockLast = map[string]int{}
)

// mockLine 挑一句台词。
// base 由「角色名 + 最后一条用户消息」哈希而来，让不同角色、不同轮次
// 天然铺开——原来只按消息长度取模，三个角色同一轮很容易撞同一句。
func mockLine(system, seed string) string {
	name := extractName(system)
	lines := mockLines[name]
	pool := "name:" + name
	if len(lines) == 0 {
		if isAnimeScene(system) {
			lines = mockAnimeLines
			pool = "anime"
		} else {
			lines = mockFallback
			pool = "fallback"
		}
	}
	return pickLine(pool, lines, fnv32(name+"\x00"+seed))
}

// pickLine 挑一句台词。
// 哈希取模仍有 1/N 的概率让同一角色连续两轮撞同一句，
// 演示里连着两条一模一样最致命，所以撞上上一句就顺手挪一格。
func pickLine(pool string, lines []string, base uint32) string {
	n := len(lines)
	idx := int(base % uint32(n))
	mockMu.Lock()
	if mockLast[pool] == idx {
		idx = (idx + 1) % n
	}
	mockLast[pool] = idx
	mockMu.Unlock()
	return lines[idx]
}

// fnv32 标准库外最简单的字符串哈希，够把 seed 铺开就行。
func fnv32(s string) uint32 {
	h := uint32(2166136261)
	for i := 0; i < len(s); i++ {
		h ^= uint32(s[i])
		h *= 16777619
	}
	return h
}
