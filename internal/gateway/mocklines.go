// 兜底台词：角色名不在表里时用（多半是用户自己造的角色）
var mockFallback = []string{
	"我在听。",
	"这个我有点想法，先说一句——先把范围定下来。",
	"嗯，接着说。",
}

// extractName 从 system prompt 里抠出角色名。
// 编排器写的是：你的名字是「林」
func extractName(system string) string {
	const marker = "你的名字是「"
	i := strings.Index(system, marker)
	if i < 0 {
		return ""
	}
	rest := system[i+len(marker):]
	j := strings.Index(rest, "」")
	if j < 0 {
		return ""
	}
	return rest[:j]
}

// mockLine 挑一句台词。用轮次做稳定选择，避免同一角色每句都一样。
func mockLine(system, seed string) string {
	name := extractName(system)
	lines, ok := mockLines[name]
	if !ok || len(lines) == 0 {
		lines = mockFallback
	}
	// 用 seed 的长度做下标，保证同一次请求内稳定、不同请求有变化
	n := len([]rune(seed))
	return lines[n%len(lines)]
}
